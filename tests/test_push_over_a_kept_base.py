WALL = ((-1, 0, 0), (8.47, 6.38, 1.82))       # the L block's wall, beam on it


def _model():
    scene = Scene()
    for loops in FACES:
        outer, *holes = [[V(*p) for p in lp] for lp in loops]
        scene.mesh.add_face(outer, holes or None)
    orient_outward(scene.mesh)
    return scene


def _face(scene, normal, centre):
    n, c = V(*normal), V(*centre)
    return next(f for f in scene.faces if not f.interior
                and V.dotProduct(f.normal().normalized(), n) > 0.999
                and (f.centroid() - c).length() < 0.02)


def _cracks(mesh) -> int:
    return sum(1 for e in mesh.edges
               if sum(1 for f in e.faces if not f.interior) % 2)


def test_the_model_is_sound():
    m = _model().mesh
    assert is_closed(m)
    assert _cracks(m) == 0


@pytest.mark.parametrize("d", [0.1, 0.34, 1.06])
def test_pushing_the_wall_out_over_the_beams_end(d):
    scene = _model()
    wall = _face(scene, *WALL)
    area = wall.area()
    before = signed_volume(scene.mesh)
    vp = T._push(scene, wall, d)
    m = scene.mesh
    assert vp.last_status is None                 # not refused
    assert is_closed(m)
    assert _cracks(m) == 0
    # The wall's face is the ring around the beam's end; the swallowed end
    # was already solid, so only the ring adds volume.
    assert abs(signed_volume(m) - (before + area * d)) < 1e-3
    # Nothing is left floating where the beam's base stood.
    assert not [f for f in m.faces if f.interior
                and abs(f.centroid().x() - 8.47) < 1e-3]


@pytest.mark.parametrize("d", [-0.1, -0.34])
def test_pulling_the_wall_back_still_works(d):
    scene = _model()
    before = signed_volume(scene.mesh)
    vp = T._push(scene, _face(scene, *WALL), d)
    assert vp.last_status is None
    assert is_closed(scene.mesh)
    assert signed_volume(scene.mesh) < before
