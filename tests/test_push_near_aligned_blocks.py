"""Pushes on a model of nearly aligned blocks, built with Ctrl pushes.

A user's model (blocks a few centimetres out of line, a bridge resting on a
pillar, kept bases inside) where most faces refused to move. Two causes:

- the orientation rays from the first block's end wall grazed the busy
  corner of the bridge and read material on both sides, so the wall was
  marked a partition although it shares plain two-face edges with the
  outside walls. Every push next to it then saw material behind the wall
  and dropped the faces it needed;
- a push could leave the solid closed but cracked (an edge with an odd
  number of boundary faces) and commit it, skewing the volume."""
