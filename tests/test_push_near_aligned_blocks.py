def _model():
    scene = Scene()
    for loops in FACES:
        outer, *holes = [[V(*p) for p in lp] for lp in loops]
        scene.mesh.add_face(outer, holes or None)
    orient_outward(scene.mesh)
    return scene


def _face(scene, normal, centre):
    n, c = V(*normal), V(*centre)
    return next(f for f in scene.faces
                if V.dotProduct(f.normal().normalized(), n) > 0.999
                and (f.centroid() - c).length() < 0.02)


def test_an_outside_wall_is_not_taken_for_a_partition():
    scene = _model()
    wall = _face(scene, (1, 0, 0), (4.94, 4.18, 0.97))   # the end wall
    assert not wall.interior
    for e in scene.mesh.edges:                 # two-face edges agree
        if len(e.faces) == 2:
            a, b = e.faces
            assert a.interior == b.interior


@pytest.mark.parametrize("d", [0.2, -0.1])
@pytest.mark.parametrize("centre", [(7.35, 3.94, 1.87), (8.18, 3.94, 1.84)])
def test_the_bridge_side_moves(centre, d):
    scene = _model()
    cracks = _boundary_cracks(scene.mesh)
    before = signed_volume(scene.mesh)
    side = _face(scene, (0, -1, 0), centre)
    area = side.area()
    vp = T._push(scene, side, d)
    m = scene.mesh
    assert vp.last_status is None                 # not refused
    assert is_closed(m)
    assert _boundary_cracks(m) <= cracks
    assert abs(signed_volume(m) - (before + d * area)) < 1e-3


@pytest.mark.slow
def test_no_push_leaves_the_solid_cracked():
    count = len(_model().faces)
    for i in range(count):
        for d in (0.2, -0.1):
            scene = _model()
            face = scene.faces[i]
            if face.interior:
                continue
            cracks = _boundary_cracks(scene.mesh)
            T._push(scene, face, d)
            assert is_closed(scene.mesh)
            assert _boundary_cracks(scene.mesh) <= cracks, (i, d)
